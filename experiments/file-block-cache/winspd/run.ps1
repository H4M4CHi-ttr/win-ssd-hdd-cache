#Requires -Version 7.2
[CmdletBinding()]
param([Parameter(Mandatory)][string] $Package, [string] $SevenZip,
      [ValidateSet('Direct', 'ServerDll', 'Recovery', 'WorkerLoss', 'ReadOnly')][string] $Transport = 'Direct')
$sdk = $Transport -ne 'Direct'
$recovery = $Transport -eq 'Recovery'
$workerLoss = $Transport -eq 'WorkerLoss'
$readOnlyTrial = $Transport -eq 'ReadOnly'

$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $false
if (!$IsWindows -or [Runtime.InteropServices.RuntimeInformation]::ProcessArchitecture -ne 'X64') {
    throw 'Requires 64-bit Windows PowerShell 7 and an x64 MSVC developer environment.'
}
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..\..'))
$manifest = Join-Path $root 'Cargo.toml'
$cargo = (Get-Command cargo.exe -CommandType Application | Select-Object -First 1).Source
$cl = (Get-Command cl.exe -CommandType Application | Select-Object -First 1).Source
if (!$SevenZip) {
    $installed = Get-Command 7z.exe -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    $SevenZip = if ($installed) { $installed.Source } else { Join-Path $env:ProgramFiles '7-Zip\7z.exe' }
}
$archiver = (Get-Item -LiteralPath $SevenZip).FullName
# This path is read only. stgtest's target is always generated by the native broker.
$packageItem = Get-Item -LiteralPath $Package
if ($packageItem -isnot [IO.FileInfo] -or $packageItem.Extension -ine '.msi' -or $packageItem.Length -ne 2195456) {
    throw 'Expected an ordinary file with the official package size.'
}
$pkg = $packageItem.FullName
$stage = Join-Path ([IO.Path]::GetTempPath()) ('file-cache-winspd-' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $stage -ErrorAction Stop | Out-Null
$fixtureRoot = Join-Path $stage 'fixtures'
$names = @('stgtest_x64.exe','stgtest-x64.exe','ioctl.h','pipe_broker.obj','file-cache-pipe-broker.exe','file-cache-pipe-test.exe')
if ($sdk) { $names += @('winspd_x64.dll','winspd-x64.dll','winspd.h','winspd_sdk.obj') }
$pkgLock = $clientLock = $dllLock = $process = $null
try {
    [IO.Directory]::CreateDirectory($fixtureRoot) | Out-Null
    $pkgLock = [IO.File]::Open($pkg, 'Open', 'Read', 'Read')
    $packageHash = (Get-FileHash -InputStream $pkgLock -Algorithm SHA256).Hash
    if ($packageHash -cne 'F1157EEF805DCBEC78A477F2B4EE5ABC0049C8A9329444E5D18CAB01D3604265') {
        throw 'Expected the official WinSpd v1.0B1 winspd-1.0.20357.msi.'
    }
    $entries = @('stgtest_x64.exe','ioctl.h')
    if ($sdk) { $entries += @('winspd.h','winspd_x64.dll') }
    $listing = @(& $archiver e -y ('-o' + $stage) -- $pkg @entries 2>&1)
    if ($LASTEXITCODE) { throw 'Could not extract client and ABI header.' }
    $client = Join-Path $stage 'stgtest-x64.exe'
    [IO.File]::Move((Join-Path $stage 'stgtest_x64.exe'), $client)
    $clientLock = [IO.File]::Open($client, 'Open', 'Read', 'Read')
    $clientHash = (Get-FileHash -InputStream $clientLock -Algorithm SHA256).Hash
    if ($clientHash -cne 'FF53AE37AD610AA851765596B3E821BD28CF2F0F68AD30991C79B423A3FB0AB7') {
        throw 'Unexpected official test client.'
    }

    if ($sdk) {
        $dll = Join-Path $stage 'winspd-x64.dll'
        [IO.File]::Move((Join-Path $stage 'winspd_x64.dll'),$dll)
        $dllLock = [IO.File]::Open($dll,'Open','Read','Read')
        if ((Get-FileHash -InputStream $dllLock -Algorithm SHA256).Hash -cne '35433B6E99C4B282A7EC07757F2206851F28DABF7BBCFFD90BF60F317E865F7B') { throw 'Unexpected official server DLL.' }
        $inc = Join-Path $stage 'winspd'
        [IO.Directory]::CreateDirectory($inc) | Out-Null
        [IO.File]::Move((Join-Path $stage 'winspd.h'),(Join-Path $inc 'winspd.h'))
        [IO.File]::Copy((Join-Path $stage 'ioctl.h'),(Join-Path $inc 'ioctl.h'),$false)
    }
    $broker = Join-Path $stage 'file-cache-pipe-broker.exe'
    $compile = @('/nologo','/TC','/std:c17','/W4','/WX','/external:anglebrackets','/external:W0',
        '/O2','/MT','/DUNICODE','/D_UNICODE',('/I' + $stage),('/Fo' + (Join-Path $stage 'pipe_broker.obj')),
        ('/Fe' + $broker),(Join-Path $PSScriptRoot 'pipe_broker.c'),'/link','/INCREMENTAL:NO','ole32.lib')
    if ($sdk) {
        $obj = Join-Path $stage 'winspd_sdk.obj'
        $sdkArgs = @('/nologo','/c','/TC','/std:c17','/W4','/WX','/external:anglebrackets','/external:W0',
            '/O2','/MT','/DUNICODE','/D_UNICODE',('/I'+$stage),('/Fo'+$obj),(Join-Path $PSScriptRoot 'winspd_sdk.c'))
        & $cl @sdkArgs
        if ($LASTEXITCODE) { throw 'Server DLL adapter compilation failed.' }
        $compile = @('/DFILE_CACHE_SDK=1') + $compile + @($obj)
    }
    & $cl @compile
    if ($LASTEXITCODE) { throw 'Native broker or ABI layout check failed.' }

    $build = @(& $cargo test --manifest-path $manifest --locked --offline -p cache-model --test file_block_cache --no-run --message-format=json)
    if ($LASTEXITCODE) { throw 'Rust test build failed.' }
    $bins = @($build | ForEach-Object {
        $item = $_ | ConvertFrom-Json
        if ($item.reason -eq 'compiler-artifact' -and $item.target.name -eq 'file_block_cache' -and $item.executable) {
            $item.executable
        }
    })
    if ($bins.Count -ne 1) { throw 'Expected exactly one test executable.' }
    $test = Join-Path $stage 'file-cache-pipe-test.exe'
    [IO.File]::Copy($bins[0], $test, $false)
    $start = [Diagnostics.ProcessStartInfo]::new($test)
    $start.WorkingDirectory = $stage
    $start.Environment['TEMP'] = $start.Environment['TMP'] = $fixtureRoot
    $start.UseShellExecute = $false
    $start.CreateNoWindow = $true
    $start.RedirectStandardOutput = $start.RedirectStandardError = $true
    $case = if ($sdk) { 'official_server_dll_over_private_pipe' } else { 'official_client_over_private_pipe' }
    $testName = if ($readOnlyTrial) { 'cache::tests::winspd::read_only::official_write_protection' } elseif ($workerLoss) { 'cache::tests::winspd::recovery::abrupt::worker_loss_and_restart' } elseif ($recovery) { 'cache::tests::winspd::recovery::restart_after_lost_write' } else { 'cache::tests::winspd::live::' + $case }
    foreach ($v in @('--ignored','--exact',$testName,'--nocapture')) {
        $start.ArgumentList.Add($v)
    }
    $process = [Diagnostics.Process]::Start($start)
    $testPid = $process.Id
    $stdout = $process.StandardOutput.ReadToEndAsync()
    $stderr = $process.StandardError.ReadToEndAsync()
    if (!$process.WaitForExit(90000)) {
        throw 'Test exceeded the overall 90 second deadline.'
    }
    $lines = $stdout.GetAwaiter().GetResult()
    $errors = $stderr.GetAwaiter().GetResult()
    if ($readOnlyTrial) {
        $receiptOk = $lines -match '(?m)^FILE_CACHE_READ_ONLY_OK\r?$' -and
            ([regex]::Matches($lines,'(?m)^READ_ONLY ')).Count -eq 7
    } elseif ($workerLoss) {
        $receiptOk = $lines -match '(?m)^FILE_CACHE_WORKER_LOSS_OK\r?$' -and
            ([regex]::Matches($lines,'(?m)^ABRUPT_PAIR ')).Count -eq 3
    } elseif ($recovery) {
        $receiptOk = $lines -match '(?m)^FILE_CACHE_RECOVERY_OK\r?$' -and
            ([regex]::Matches($lines,'(?m)^RECOVERY_PAIR ')).Count -eq 2
    } else {
        $marker = if ($sdk) { 'FILE_CACHE_WINSPD_SERVER_DLL_OK' } else { 'FILE_CACHE_WINSPD_OK' }
        $cases = if ($sdk) { 13 } else { 9 }
        $receiptOk = $lines -match ('(?m)^' + $marker + '\r?$') -and
            (!$sdk -or ([regex]::Matches($lines,'(?m)^SERVER_DLL [\w-]+ client_requests=')).Count -eq $cases) -and
            ([regex]::Matches($lines,'WINSPD [\w-]+ requests=')).Count -eq $cases
    }
    if ($process.ExitCode -ne 0 -or !$receiptOk -or $lines -notmatch 'test result: ok\. 1 passed;') {
        throw ("Live smoke failed (exit {0}). {1} {2}" -f $process.ExitCode, $lines, $errors)
    }
    $lines.TrimEnd()
} finally {
    if ($process) {
        if (!$process.HasExited) {
            $process.Kill($true)
            if (!$process.WaitForExit(5000)) { throw 'Test process did not terminate.' }
        }
        $process.Dispose()
    }
    if ($dllLock) { $dllLock.Dispose() }
    if ($clientLock) { $clientLock.Dispose() }
    if ($pkgLock) { $pkgLock.Dispose() }
    # Only the fixed files in the fresh, owned directory can be removed.
    foreach ($name in $names) {
        $owned = Join-Path $stage $name
        if ([IO.File]::Exists($owned)) { [IO.File]::Delete($owned) }
    }
    if ([IO.Directory]::Exists($fixtureRoot)) {
        $reparse = [IO.FileAttributes]::ReparsePoint
        if ($process) {
            foreach ($dir in [IO.DirectoryInfo]::new($fixtureRoot).EnumerateDirectories()) {
                if ($dir.Name -notmatch ('^win-cache-file-test-' + $testPid + '-[0-9]+$') -or
                    ($dir.Attributes -band $reparse)) { throw 'Unexpected leftover fixture directory.' }
                foreach ($entry in $dir.EnumerateFileSystemInfos()) {
                    if ($entry -isnot [IO.FileInfo] -or ($entry.Attributes -band $reparse) -or
                        $entry.Name -cnotin @('origin.img','cache.img')) { throw 'Unexpected leftover fixture entry.' }
                    $entry.Delete()
                }
                $dir.Delete($false)
            }
        }
        [IO.Directory]::Delete($fixtureRoot, $false)
    }
    $inc = Join-Path $stage 'winspd'
    if ($sdk -and [IO.Directory]::Exists($inc)) {
        foreach ($h in @('ioctl.h','winspd.h')) { [IO.File]::Delete((Join-Path $inc $h)) }
        [IO.Directory]::Delete($inc,$false)
    }
    [IO.Directory]::Delete($stage, $false)
}
